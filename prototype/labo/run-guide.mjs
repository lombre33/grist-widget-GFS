check('la sous-démarche a sa mère et ses étapes', rows.Title.length === 2 && rows.Parent[1] === rows.id[0] && rows.Steps[1] === 'Saisir la demande\nFaire valider', rows);
check('elle hérite du contact de sa mère', (await win.innerText()).includes('Service RH'), await win.innerText());
await lab.shotPanel(run, '9-fiche');
// modifier : seul le titre change
