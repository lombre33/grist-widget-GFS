// Le module Guide (demande du porteur du 27/11) dans un vrai Grist (grist-static), à 700 × 400, à la vraie souris et au vrai clavier : GFS démarre avec le bouton du guide, la fenêtre
// s'ouvre sans rien écrire et dit « aucun guide », puis aucune erreur ni avertissement de GFS. LAB_LANG=fr|en, LAB_SCHEME=light|dark.
import { startLab } from './lab-setup.mjs';
import { check } from './lab-common.mjs';
import { seedAnnuaire } from './jeu-annuaire.mjs';
import { closeModules } from './lab-gestes.mjs';

const lang = process.env.LAB_LANG || 'fr';
const scheme = process.env.LAB_SCHEME || 'light';
const run = `guide-${lang}-${scheme}`;
const lab = await startLab({ lang, colorScheme: scheme });
const { page } = lab;
const problems = [];
page.on('console', m => { if ((m.type() === 'warning' || m.type() === 'error') && /^GFS|Refused|CSP|Content Security/.test(m.text())) problems.push(m.text()); });
page.on('pageerror', error => problems.push(error.message));
await lab.fitPanel(undefined, 700, 400);
const frame = lab.frame;
await frame.waitForFunction(() => document.body.dataset.gfsFirstRun === 'done', null, { timeout: 30000 }).catch(() => {});
check('GFS démarre (pas de « GFS ne démarre pas »)', (await frame.evaluate(() => document.body.dataset.gfs)) !== 'starting', await frame.evaluate(() => document.body.dataset.gfs));
await closeModules(page, frame);
await seedAnnuaire(frame);
await page.waitForTimeout(500);
await lab.forgetActions();
const tables = () => frame.evaluate(() => grist.docApi.listTables());
const button = frame.locator('.ex-title-row button', { has: frame.locator('use[href="#i-guide"]') });
check('le bouton du guide est dans l’explorateur', (await button.count()) === 1);
check('le bouton du guide est dans la barre', (await frame.locator('#floater-guide').count()) === 1);
await button.click();
const win = frame.locator('.mod.gd');
await win.waitFor({ state: 'visible' });
await page.waitForTimeout(500);
check('sans guide, la fenêtre le dit et propose d’en créer un', (await win.locator('.btn.primary').count()) >= 1, await win.innerText());
check('ouvrir ne crée aucune table', !(await tables()).includes('GFS_Guides'));
await lab.shotPanel(run, '1-vide');

// 2. Un guide neuf : la table des démarches créée avec l'accord, l'annuaire, un rôle ; puis la lecture.
await win.locator('.btn.primary').first().click();
const setup = frame.locator('.mod.gd-set');
await setup.waitFor({ state: 'visible' });
await setup.locator('[data-fk="set-name"]').fill('Démarches du personnel');
await setup.locator('[data-act="table"]').click();
await frame.locator('.mod.pk').waitFor({ state: 'visible' });
await lab.shotPanel(run, '2-choix-table');
await frame.locator('.mod.pk .wk-item', { hasText: /Créer|Create/ }).first().click();
const ask = frame.locator('.mod.ask, .mod.cf, .mod-confirm, [role="alertdialog"]').first();
await page.waitForTimeout(400);
await lab.shotPanel(run, '3-accord');
const consent = frame.locator('.mod', { hasText: /Guide_Procedures/ }).last();
await consent.locator('.btn.primary').click();
await page.waitForTimeout(1200);
const names = await tables();
check('la table des démarches est créée avec l’accord de la personne', names.includes('Guide_Procedures'), names);
check('rien d’autre n’est créé encore (pas de GFS_Guides avant l’enregistrement)', !names.includes('GFS_Guides'), names);
const colsOf = async table => (await frame.evaluate(t => grist.docApi.fetchTable(t), table));
const made = await colsOf('Guide_Procedures');
check('ses colonnes : Title, Keywords, Steps, Details, Parent', ['Title', 'Keywords', 'Steps', 'Details', 'Parent'].every(c => c in made), Object.keys(made));
await lab.shotPanel(run, '4-table-creee');
console.log('SETUP', (await setup.innerText()).replace(/\n+/g, ' | ').slice(0, 500));
await setup.locator('[data-act="directory"]').click();
await frame.locator('.mod.pk .wk-item').first().click();
await page.waitForTimeout(300);
await setup.locator('[data-act="role-add"]').click();
await page.waitForTimeout(400);
await lab.shotPanel(run, '5-role');
await frame.locator('.mod.pk .wk-item', { hasText: /Créer une colonne|Create a column/ }).first().click();
const nc = frame.locator('.mod', { has: frame.locator('[data-fk="nc-name"]') });
await nc.waitFor({ state: 'visible' });
await nc.locator('[data-fk="nc-name"]').fill('Contact');
await nc.locator('[data-fk="nc-ok"]').click();
await page.waitForTimeout(1000);
check('la colonne de rôle est créée à la demande', 'Contact' in (await colsOf('Guide_Procedures')));
await setup.locator('[data-fk="set-save"]').click();
const consentGuides = frame.locator('.mod', { hasText: /GFS_Guides/ }).last();
await consentGuides.locator('.btn.primary').click();
await page.waitForTimeout(1500);
const after = await tables();
check('GFS_Guides naît avec l’accord, et seulement alors', after.includes('GFS_Guides'), after);
const row = await colsOf('GFS_Guides');
check('une ligne par guide, avec son nom et sa table', row.Name && row.Name[0] === 'Démarches du personnel' && row.Table[0] === 'Guide_Procedures', row);
check('la fenêtre montre le guide créé (vide : aucune démarche)', (await win.innerText()).includes('Démarches du personnel'), await win.innerText());
await lab.shotPanel(run, '8-guide-cree');
// Des démarches ajoutées dans la table par la personne : le guide les lit à la réouverture.
await frame.evaluate(() => grist.docApi.applyUserActions([['BulkAddRecord', 'Guide_Procedures', [null, null], { Title: ['Congés', 'Poser des congés'], Parent: [0, 1], Contact: ['', 'Service RH'] }]]));
await page.keyboard.press('Escape');
await win.waitFor({ state: 'detached' });
await button.click();
await win.waitFor({ state: 'visible' });
await page.waitForTimeout(800);
check('les démarches écrites dans la table apparaissent', (await win.innerText()).includes('Congés'), await win.innerText());
await win.locator('.gd-tile', { hasText: 'Congés' }).click();
await win.locator('.gd-kid', { hasText: 'Poser des congés' }).click();
await page.waitForTimeout(500);
check('la fiche dit le rôle hérité ou propre', (await win.innerText()).includes('Service RH'), await win.innerText());
await lab.shotPanel(run, '9-fiche');
await page.keyboard.press('Escape');
await win.waitFor({ state: 'detached' });
const written = await lab.actions();
check('GFS n’écrit que ce que la personne a demandé : la table des démarches (ses colonnes, la mère, le rôle), GFS_Guides et sa ligne (les pages et sections de Grist suivent l’ajout d’une table)',
  written.every(action => /^(AddTable|AddColumn|SetDisplayFormula|AddRecord|BulkAddRecord|UpdateRecord) (Guide_Procedures|GFS_Guides|_grist_Pages|_grist_Views_section)/.test(action)) && !written.some(action => /Personnes|Structures|Postes|Clients/.test(action)), written);
check('aucun avertissement ni erreur de GFS ou de politique de sécurité', problems.length === 0, problems);
await lab.browser.close();
